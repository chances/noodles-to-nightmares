/** A select-list group: a Sanny class, `Script` for opcodes with no class and the project's own helpers, or `Monitors` for the latch conditions the editor writes. */
export type Group = typeof SANNY_CLASSES[number] | "Script" | "Monitors";

export interface StepDescriptor extends Descriptor {
  group: Group;
  /**
   * Gives the card a "Shown" checkbox, checked when `on`. Flipping it turns the card into its `partner`, so the
   * card's title and Sanny follow the checkbox: "Add Blip" when shown, "Remove Blip" when not. A list `partner`
   * is flipped to the form the card was last flipped from, or its first entry. `label` names the checkbox and
   * defaults to "Shown".
   */
  shown?: { on: boolean; partner: string | string[]; label?: string };
}

export interface CondDescriptor extends Descriptor {
  group: Group;
  /** Lines that run before the `if`; `lines` holds the test. `pre` lines may use `{field}` slots like `lines`. */
  pre?: string[];
  locals?: string[];
  /**
   * The 2D and 3D descriptors of one function share a `pair` name, and each names its own `mode`.
   *
   * @remarks The add menu offers only the descriptor without `mode: "2D"`, and the card's switch flips between the
   * two forms. A `spot` field reads `{spot}_X` and `{spot}_Y` in 2D and adds `{spot}_Z` in 3D, so one spot serves
   * both forms.
   */
  pair?: string;
  mode?: CardMode;
}

